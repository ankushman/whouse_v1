// ---- TypeScript Interfaces ----

export interface Warehouse {
  id: string;
  name: string;
  city: string;
  state: string;
  managerName: string;
  managerAvatar: string;
  capacity: number;
  capacityUsed: number;
  inventoryAccuracy: number;
  /** Alias used by some views (e.g. warehouse-map) */
  accuracy?: number;
  forkliftCount: number;
  forkliftActive: number;
  todayOrders: number;
  pendingTasks: number;
  healthScore: number;
  status: "green" | "amber" | "red";
  alerts: number;
}

export interface KPIData {
  totalWarehouses: number;
  activeShipments: number;
  pendingGRN: number;
  inventoryAccuracy: number;
  todaysDispatches: number;
  dockToStockTime: number;
  slaAchievement: number;
  equipmentUtilization: number;
  costPerShipment: number;
  warehouseOccupancy: number;
  productivity: number;
}

export interface KPIMetric extends KPIData {
  trend: "up" | "down";
  trendValue: number;
}

export interface MonthlyTrend {
  month: string;
  domestic: number;
  imported: number;
}

export interface OutboundMonthlyTrend {
  month: string;
  dispatched: number;
  delivered: number;
  returned: number;
}

export interface WarehousePerformance {
  name: string;
  inbound: number;
  outbound: number;
  accuracy: number;
  sla: number;
}

export interface DispatchDay {
  day: string;
  dispatched: number;
  onTime: number;
  delayed: number;
}

export interface CostEntry {
  month: string;
  labor: number;
  transport: number;
  equipment: number;
  storage: number;
  total: number;
}

export interface ThroughputDay {
  day: string;
  inbound: number;
  outbound: number;
}

export interface Equipment {
  id: string;
  name: string;
  warehouse: string;
  type: string;
  batteryLevel: number;
  status: "active" | "maintenance" | "idle" | "charging";
  lastMaintenance: string;
  nextMaintenance: string;
  hoursUsed: number;
  downtime: number;
}

export interface SLAEntry {
  name: string;
  target: number;
  achieved: number;
  breach: number;
}

export interface AccuracyTrendEntry {
  month: string;
  accuracy: number;
}

export interface Employee {
  id: string;
  name: string;
  role: string;
  warehouse: string;
  avatar: string;
  shift: "Morning" | "Afternoon" | "Night" | "Off Duty";
  attendance: number;
  tasksCompleted: number;
  productivity: number;
  overtime: number;
  errorRate: number;
  rank: number;
}

export interface TransportVehicle {
  id: string;
  registration: string;
  type: "Truck" | "Container" | "Flatbed";
  driver: string;
  route: string;
  status: "in-transit" | "available" | "maintenance" | "delayed";
  eta: string;
  currentLocation: string;
  deliveriesCompleted: number;
  deliveriesTotal: number;
}

export interface Alert {
  id: string;
  type: "sla" | "productivity" | "inventory" | "dispatch" | "equipment" | "capacity";
  severity: "critical" | "warning" | "info";
  title: string;
  message: string;
  warehouse: string;
  timestamp: string;
  acknowledged: boolean;
}

export interface TimelineStep {
  step: number;
  label: string;
  duration: string;
  user: string;
  status: "completed" | "in-progress" | "pending";
  timestamp: string;
}

export interface InboundShipment {
  id: string;
  invoice: string;
  supplier: string;
  type: "Domestic" | "Imported";
  warehouse: string;
  status: string;
  currentStep: number;
  timeline: TimelineStep[];
  slaProgress: number;
  createdAt: string;
}

export interface OutboundShipment {
  id: string;
  invoice: string;
  customer: string;
  warehouse: string;
  pickingType: "Batch" | "Wave" | "Single";
  picker: string;
  packer: string;
  vehicle: string;
  status: "Pending" | "Picking" | "Packing" | "Ready" | "Dispatched" | "Delivered";
  createdAt: string;
  dispatchTime: string | null;
  deliveryTime: string | null;
}

export interface InventoryItem {
  id: string;
  sku: string;
  partName: string;
  category: "Engine" | "Transmission" | "Body" | "Electrical" | "Suspension" | "Brakes";
  warehouse: string;
  quantity: number;
  minStock: number;
  maxStock: number;
  abcClass: "A" | "B" | "C";
  lastCount: string;
  variance: number;
  location: string;
  daysSinceLastCount: number;
}

export interface ManpowerDay {
  day: string;
  morning: number;
  afternoon: number;
  night: number;
}

